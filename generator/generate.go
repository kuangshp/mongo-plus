// Package generator 根据 schema 或手写 Entity 生成 DAO 和 Repository。
package generator

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/kuangshp/mongo-plus/schema"
)

const generated = "// Code generated by mongoplus. DO NOT EDIT.\n"

// Generate 读取配置中的 JSON 文件并生成代码，不连接数据库。
func Generate(c schema.Config) ([]string, error) {
	if err := c.Normalize(); err != nil {
		return nil, err
	}
	entities, err := schema.LoadEntities(c)
	if err != nil {
		return nil, err
	}
	return GenerateEntities(c, entities)
}

// GenerateEntities 生成已经校验的元数据，支持手写 Entity 路线。
func GenerateEntities(c schema.Config, entities []schema.Entity) ([]string, error) {
	if err := c.Normalize(); err != nil {
		return nil, err
	}
	type output struct {
		path     string
		data     []byte
		preserve bool
	}
	outputs := []output{}
	seen := map[string]bool{}
	for _, entity := range entities {
		if err := entity.Normalize(c, strings.TrimSuffix(entity.Entity, "Entity")); err != nil {
			return nil, err
		}
		if entity.ExternalModel && entity.ModelPackage == "" {
			return nil, fmt.Errorf("手写实体缺少 ModelPackage")
		}
		base := strings.ToLower(strings.TrimSuffix(entity.Entity, "Entity"))
		if seen[base] {
			return nil, fmt.Errorf("生成文件名称冲突 %s", base)
		}
		seen[base] = true
		modelImport := c.ImportPath("model")
		if entity.ExternalModel {
			modelImport = entity.ModelPackage
		}
		model, dao, repo, extension, err := render(entity, modelImport, c)
		if err != nil {
			return nil, err
		}
		if !entity.ExternalModel {
			outputs = append(outputs, output{filepath.Join(c.ModelPkgPath, base+"_entity.go"), model, false})
		}
		outputs = append(outputs, output{filepath.Join(c.OutPath, base+"_fields_gen.go"), dao, false}, output{filepath.Join(c.RepoPath, base+"_gen.go"), repo, false}, output{filepath.Join(c.RepoPath, base+".go"), extension, true})
		if c.DtoPath != "" {
			dto, err := renderDTO(entity, c)
			if err != nil {
				return nil, err
			}
			outputs = append(outputs, output{filepath.Join(c.DtoPath, base+"_dto.go"), dto, true})
		}
		if c.VoPath != "" {
			vo, err := renderVO(entity, modelImport, c)
			if err != nil {
				return nil, err
			}
			outputs = append(outputs, output{filepath.Join(c.VoPath, base+"_vo.go"), vo, true})
		}
	}
	// 所有文件先渲染/格式校验；生成文件带标记，拒绝覆盖同名手写文件。
	for _, out := range outputs {
		old, err := os.ReadFile(out.path)
		if err != nil && !os.IsNotExist(err) {
			return nil, err
		}
		if err == nil && !out.preserve && !bytes.HasPrefix(old, []byte(generated)) {
			return nil, fmt.Errorf("拒绝覆盖非生成文件 %s", out.path)
		}
	}
	written := []string{}
	for _, out := range outputs {
		if out.preserve {
			if _, err := os.Stat(out.path); err == nil {
				continue
			} else if !os.IsNotExist(err) {
				return nil, err
			}
		}
		if err := writeAtomic(out.path, out.data); err != nil {
			return nil, err
		}
		written = append(written, out.path)
	}
	return written, nil
}

func writeAtomic(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".mongoplus-*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err = f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err = f.Chmod(0644); err != nil {
		f.Close()
		return err
	}
	if err = f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}

func render(e schema.Entity, modelImport string, c schema.Config) (model, dao, repo, extension []byte, err error) {
	root := e.Entity
	fields := effectiveFields(e)
	var models strings.Builder
	fmt.Fprintf(&models, "// %s %s\ntype %s struct {\n", root, comment(e.Comment), root)
	for _, f := range fields {
		typ := goType(f, root+f.GoName)
		bsonName := f.Name
		if f.Name == "_id" || (!f.Required && !f.Nullable && (strings.HasPrefix(f.Type, "[]") || f.Type == "json" || f.Type == "bytes")) {
			bsonName += ",omitempty"
		}
		jsonName := f.Name
		if f.Name == "_id" {
			jsonName = "id"
		}
		fmt.Fprintf(&models, "%s %s `bson:%s json:%s` // %s\n", f.GoName, typ, strconv.Quote(bsonName), strconv.Quote(jsonName), comment(f.Comment))
	}
	models.WriteString("}\n")
	for _, f := range fields {
		renderNested(&models, f, root+f.GoName)
	}
	model, err = source(c.PackageName("model"), models.String(), nil)
	if err != nil {
		return
	}
	type daoField struct{ name, path, typ, constructor string }
	all := []daoField{}
	names := map[string]bool{}
	var add func(schema.Field, string, string, string) error
	add = func(f schema.Field, name, path, nested string) error {
		if names[name] {
			return fmt.Errorf("DAO 字段名称冲突: %s", name)
		}
		names[name] = true
		typ := goType(f, nested)
		if f.NativeGoType == "" && strings.Contains(typ, root) {
			typ = strings.ReplaceAll(typ, root, "model."+root)
		}
		var ft, ctor string
		switch {
		case f.Type == "string" && !f.Nullable && f.NativeGoType == "":
			ft = "field.String"
			ctor = "field.NewString"
		case (f.Type == "int32" || f.Type == "int64" || f.Type == "float64") && !f.Nullable:
			ft = "field.Numeric[" + typ + "]"
			ctor = "field.NewNumeric[" + typ + "]"
		case strings.HasPrefix(f.Type, "[]") && strings.HasPrefix(typ, "[]") && !f.Nullable:
			ft = "field.Array[" + strings.TrimPrefix(typ, "[]") + "]"
			ctor = "field.NewArray[" + strings.TrimPrefix(typ, "[]") + "]"
		default:
			ft = "field.Field[" + typ + "]"
			ctor = "field.New[" + typ + "]"
		}
		all = append(all, daoField{name, path, ft, ctor})
		for _, child := range f.Fields {
			if err := add(child, name+child.GoName, path+"."+child.Name, nested+child.GoName); err != nil {
				return err
			}
		}
		return nil
	}
	for _, f := range fields {
		if err = add(f, f.GoName, f.Name, root+f.GoName); err != nil {
			return
		}
	}
	var daos strings.Builder
	fmt.Fprintf(&daos, "// %s 是 %s 的 BSON 查询字段。\nvar %s = struct {\n", root, comment(e.Comment), root)
	for _, f := range all {
		fmt.Fprintf(&daos, "%s %s\n", f.name, f.typ)
	}
	daos.WriteString("}{\n")
	for _, f := range all {
		fmt.Fprintf(&daos, "%s: %s(%q),\n", f.name, f.constructor, f.path)
	}
	daos.WriteString("}\n")
	dao, err = source(c.PackageName("dao"), daos.String(), map[string]string{"field": "github.com/kuangshp/mongo-plus/field", "model": modelImport})
	if err != nil {
		return
	}
	var repos strings.Builder
	name := strings.TrimSuffix(root, "Entity")
	idType := goScalar(e.ID.Type)
	fmt.Fprintf(&repos, "// iDefault%sRepository 的基础方法签名随生成代码更新。\ntype iDefault%sRepository interface { mongoplus.Contract[model.%s,%s] }\n", name, name, root, idType)
	fmt.Fprintf(&repos, "// default%sRepository 实现生成的基础仓储，业务扩展在同名非生成文件。\ntype default%sRepository struct {\n *mongoplus.Repository[model.%s, %s]\n}\n", name, name, root, idType)
	fmt.Fprintf(&repos, "// newDefault%sRepository 使用生成时解析的全局/实体配置。\nfunc newDefault%sRepository(db *mongoplus.Database) *default%sRepository {\n return &default%sRepository{mongoplus.MustRepository[model.%s,%s](db,mongoplus.CollectionConfig{Name:%q,ID:mongoplus.IDConfig{Type:%q,Generation:%q},SoftDelete:%t,Timestamps:%t,TenantField:%q})}\n}\n", name, name, name, name, root, idType, e.Collection, e.ID.Type, e.ID.Generation, *e.SoftDelete, *e.Timestamps, e.Runtime().TenantField)
	repo, err = source(c.PackageName("repository"), repos.String(), map[string]string{"mongoplus": "github.com/kuangshp/mongo-plus", "model": modelImport})
	if err != nil {
		return
	}
	// 将接口的泛型基础方法集中维护在运行时 Contract，避免生成文件反复复制方法签名。
	ext := fmt.Sprintf("// %[1]sRepository 是业务扩展接口；此文件首次创建后不再覆盖。\ntype %[1]sRepository interface {\n iDefault%[1]sRepository\n}\n\ntype custom%[1]sRepository struct { *default%[1]sRepository }\n\nvar _ %[1]sRepository = (*custom%[1]sRepository)(nil)\n\n// New%[1]sRepository 创建仓储并复用传入的数据库连接。\nfunc New%[1]sRepository(db *mongoplus.Database) %[1]sRepository {\n return &custom%[1]sRepository{newDefault%[1]sRepository(db)}\n}\n", name)
	extension, err = source(c.PackageName("repository"), ext, map[string]string{"mongoplus": "github.com/kuangshp/mongo-plus", "model": modelImport})
	if err == nil {
		extension = bytes.Replace(extension, []byte(generated), nil, 1)
	}
	return
}

func effectiveFields(e schema.Entity) []schema.Field {
	fields := []schema.Field{{Name: "_id", GoName: "ID", Type: e.ID.Type, Comment: "主键"}}
	fields = append(fields, e.Fields...)
	if e.Tenant != nil {
		fields = append(fields, schema.Field{Name: e.Tenant.Name, GoName: schema.GoName(e.Tenant.Name), Type: e.Tenant.Type, Comment: "租户隔离字段"})
	}
	if *e.Timestamps {
		fields = append(fields, schema.Field{Name: "created_at", GoName: "CreatedAt", Type: "datetime", Comment: "创建时间"}, schema.Field{Name: "updated_at", GoName: "UpdatedAt", Type: "datetime", Comment: "更新时间"})
	}
	if *e.SoftDelete {
		fields = append(fields, schema.Field{Name: "deleted_at", GoName: "DeletedAt", Type: "datetime", Nullable: true, Comment: "逻辑删除时间；nil 表示未删除"})
	}
	return fields
}

func goScalar(typ string) string {
	switch typ {
	case "objectId":
		return "bson.ObjectID"
	case "datetime":
		return "time.Time"
	case "decimal128":
		return "bson.Decimal128"
	case "bytes":
		return "[]byte"
	case "json":
		return "bson.M"
	}
	return typ
}

func goType(f schema.Field, nested string) string {
	if f.NativeGoType != "" {
		return f.NativeGoType
	}
	base := strings.TrimPrefix(f.Type, "[]")
	typ := goScalar(base)
	if base == "object" {
		typ = nested
	}
	if strings.HasPrefix(f.Type, "[]") {
		typ = "[]" + typ
	}
	if f.Nullable {
		typ = "*" + typ
	}
	return typ
}

func renderNested(out *strings.Builder, f schema.Field, name string) {
	if strings.TrimPrefix(f.Type, "[]") != "object" {
		return
	}
	fmt.Fprintf(out, "// %s %s。\ntype %s struct {\n", name, comment(f.Comment), name)
	for _, child := range f.Fields {
		fmt.Fprintf(out, "%s %s `bson:%s json:%s` // %s\n", child.GoName, goType(child, name+child.GoName), strconv.Quote(child.Name), strconv.Quote(child.Name), comment(child.Comment))
	}
	out.WriteString("}\n")
	for _, child := range f.Fields {
		renderNested(out, child, name+child.GoName)
	}
}

func comment(value string) string { return strings.NewReplacer("\r", " ", "\n", " ").Replace(value) }

func source(pkg, body string, imports map[string]string) ([]byte, error) {
	// 从 AST 的 SelectorExpr 检查使用的包，避免只有注释中出现包名而生成未使用导入。
	file, err := parser.ParseFile(token.NewFileSet(), "generated.go", "package "+pkg+"\n"+body, 0)
	if err != nil {
		return nil, err
	}
	used := map[string]bool{}
	astInspect(file, used)
	all := map[string]string{"bson": "go.mongodb.org/mongo-driver/v2/bson", "time": "time"}
	for name, path := range imports {
		all[name] = path
	}
	keys := []string{}
	for name := range all {
		if used[name] {
			keys = append(keys, name)
		}
	}
	sort.Strings(keys)
	var out strings.Builder
	out.WriteString(generated + "package " + pkg + "\n")
	if len(keys) > 0 {
		out.WriteString("import (\n")
		for _, name := range keys {
			fmt.Fprintf(&out, "%s %q\n", name, all[name])
		}
		out.WriteString(")\n")
	}
	out.WriteString(body)
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("生成 Go 代码: %w", err)
	}
	return formatted, nil
}

func astInspect(file *ast.File, used map[string]bool) {
	ast.Inspect(file, func(node ast.Node) bool {
		if selector, ok := node.(*ast.SelectorExpr); ok {
			if name, ok := selector.X.(*ast.Ident); ok {
				used[name.Name] = true
			}
		}
		return true
	})
}
